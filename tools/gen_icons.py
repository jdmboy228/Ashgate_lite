#!/usr/bin/env python3
"""Builds ui-lite/js/icons.js from the monochrome SVGs in design/icons.

Run from the repository root: python3 tools/gen_icons.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "icons"
OUT = ROOT / "ui-lite" / "js" / "icons.js"


def compact(svg: str) -> str:
    svg = re.sub(r"\s*\n\s*", "", svg.strip())
    return svg.replace(' xmlns="http://www.w3.org/2000/svg"', "")


def main() -> None:
    icons = {p.stem: compact(p.read_text()) for p in sorted(SRC.glob("*.svg"))}
    body = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in icons.items())
    OUT.write_text(
        "// Generated by tools/gen_icons.py from design/icons. Do not edit.\n"
        "// Fluent UI System Icons (MIT); monochrome icons use currentColor.\n"
        f"export const icons = {{\n{body},\n}};\n"
    )


if __name__ == "__main__":
    main()
